-- Configuración del contexto
USE ROLE SYSADMIN;
USE WAREHOUSE CAFE_ANDINO_WH;
USE DATABASE CAFE_ANDINO_DB;
USE SCHEMA CAFE_ANDINO_ESQUEMA;

-- Creación de formatos de archivo
CREATE FILE FORMAT IF NOT EXISTS CSV_FORMAT
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    ENCODING = 'UTF8'
    NULL_IF = ('NULL', 'null', '');

CREATE FILE FORMAT IF NOT EXISTS JSON_FORMAT
    TYPE = 'JSON'
    STRIP_OUTER_ARRAY = FALSE;

-- Creación de tablas base
CREATE TABLE IF NOT EXISTS VENTAS (
    ID_VENTA INTEGER,
    FECHA DATE,
    TIENDA VARCHAR(50),
    PRODUCTO VARCHAR(50),
    CANTIDAD INTEGER,
    PRECIO_UNIT NUMBER(10, 2)
);

CREATE TABLE IF NOT EXISTS PEDIDOS_RAW (
    DATOS VARIANT,
    NOMBRE_ARCHIVO VARCHAR(255),
    FECHA_CARGA TIMESTAMP_NTZ
);

-- Creación de stages internos
CREATE STAGE IF NOT EXISTS VENTAS_STAGE
    FILE_FORMAT = CSV_FORMAT;

CREATE STAGE IF NOT EXISTS PEDIDOS_STAGE
    FILE_FORMAT = JSON_FORMAT;

CREATE STAGE IF NOT EXISTS PEDIDOS_PIPE_STAGE
    FILE_FORMAT = JSON_FORMAT;
