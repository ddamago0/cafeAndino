-- Configuración del contexto
USE ROLE SYSADMIN;
USE WAREHOUSE CAFE_ANDINO_WH;
USE DATABASE CAFE_ANDINO_DB;
USE SCHEMA CAFE_ANDINO_ESQUEMA;

-- Comprobación del stage
LIST @VENTAS_STAGE;

-- Validación previa de errores
COPY INTO VENTAS
FROM @VENTAS_STAGE/ventas_1.csv
FILE_FORMAT = CSV_FORMAT
VALIDATION_MODE = RETURN_ERRORS;

-- Carga de filas válidas
COPY INTO VENTAS
FROM @VENTAS_STAGE/ventas_1.csv
FILE_FORMAT = CSV_FORMAT
ON_ERROR = CONTINUE;

-- Registro de filas rechazadas
CREATE TABLE IF NOT EXISTS VENTAS_RECHAZADAS AS
SELECT * FROM TABLE(VALIDATE(VENTAS, JOB_ID => '_last'));

-- Consulta de filas rechazadas
SELECT * FROM VENTAS_RECHAZADAS;

-- Verificación de registros cargados
SELECT COUNT(*) AS TOTAL_FILAS FROM VENTAS;

-- Consulta de ventas cargadas
SELECT * FROM VENTAS ORDER BY ID_VENTA;

-- Historial de carga de ventas
SELECT
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ROW_PARSED,
    ERROR_COUNT,
    FIRST_ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
    TABLE_NAME => 'VENTAS',
    START_TIME => DATEADD(HOURS, -1, CURRENT_TIMESTAMP())
));
