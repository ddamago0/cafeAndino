-- Configuración del contexto
USE ROLE SYSADMIN;
USE WAREHOUSE CAFE_ANDINO_WH;
USE DATABASE CAFE_ANDINO_DB;
USE SCHEMA CAFE_ANDINO_ESQUEMA;

-- Creación de Snowpipe
CREATE PIPE IF NOT EXISTS PEDIDOS_PIPE
    AUTO_INGEST = FALSE
AS
COPY INTO PEDIDOS_RAW (DATOS, NOMBRE_ARCHIVO, FECHA_CARGA)
FROM (
    SELECT
        $1,
        METADATA$FILENAME,
        CURRENT_TIMESTAMP()
    FROM @PEDIDOS_PIPE_STAGE
)
FILE_FORMAT = JSON_FORMAT;

-- Comprobación del stage del pipe
LIST @PEDIDOS_PIPE_STAGE;

-- Refresco manual de Snowpipe
ALTER PIPE PEDIDOS_PIPE REFRESH;

-- Estado del pipe
SELECT SYSTEM$PIPE_STATUS('PEDIDOS_PIPE');

-- Verificación de pedidos sin duplicados
SELECT COUNT(*) AS TOTAL_PEDIDOS FROM PEDIDOS_RAW;

-- Consulta de control de pedidos
SELECT
    DATOS:pedido_id::INTEGER AS PEDIDO_ID,
    NOMBRE_ARCHIVO,
    FECHA_CARGA
FROM PEDIDOS_RAW
ORDER BY PEDIDO_ID;

-- Historial de carga del pipe
SELECT
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ROW_PARSED,
    ERROR_COUNT,
    FIRST_ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
    TABLE_NAME => 'PEDIDOS_RAW',
    START_TIME => DATEADD(HOURS, -1, CURRENT_TIMESTAMP())
));

-- Verificación del detalle acumulado
SELECT COUNT(*) AS TOTAL_ITEMS FROM PEDIDOS_DETALLE;

-- Consulta del detalle completo
SELECT * FROM PEDIDOS_DETALLE ORDER BY PEDIDO_ID, PRODUCTO;
